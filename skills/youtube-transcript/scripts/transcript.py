#!/usr/bin/env python3
"""Get YouTube transcripts through the YouTube Transcript Scraper on Apify.

Works from servers and cloud machines, where YouTube blocks direct requests.
Needs only the Python standard library and an APIFY_TOKEN environment variable.

Examples:
    transcript.py https://www.youtube.com/watch?v=dQw4w9WgXcQ
    transcript.py https://youtu.be/dQw4w9WgXcQ --lang pt --translate en
    transcript.py @veritasium --max-videos 5 --format srt --out subs/
"""
import argparse
import json
import os
import sys
import urllib.error
import urllib.request

ACTOR = "andracore~youtube-transcript-scraper"
ENDPOINT = f"https://api.apify.com/v2/acts/{ACTOR}/run-sync-get-dataset-items"
# Highest price per transcript (Apify free plan). Paid plans pay less, so this caps the cost of a run.
PRICE_USD = 0.004
TOKEN_HELP = (
    "APIFY_TOKEN is not set.\n"
    "1. Create a free Apify account: https://console.apify.com/sign-up (the free plan includes US$ 5 of credit every month)\n"
    "2. Copy your API token: https://console.apify.com/settings/integrations\n"
    "3. export APIFY_TOKEN=<your token>"
)
EXTENSIONS = {"srt": "srt", "vtt": "vtt", "text": "txt", "timestamped": "json", "all": "json"}


def parse_args():
    p = argparse.ArgumentParser(description="Get YouTube transcripts, subtitles and captions.")
    p.add_argument("urls", nargs="+", help="video, Shorts, playlist or channel links, @handles or 11-character video IDs")
    p.add_argument("--lang", default="en", help="preferred caption language, two letters (default: en)")
    p.add_argument("--translate", metavar="LANG", help="machine-translate the transcript into this language")
    p.add_argument("--format", choices=sorted(EXTENSIONS), default="text", help="output format (default: text)")
    p.add_argument("--max-videos", type=int, default=10, help="stop after this many videos (default: 10)")
    p.add_argument("--no-auto", action="store_true", help="skip videos that only have auto-generated captions")
    p.add_argument("--out", metavar="DIR", help="write one file per video into DIR instead of printing")
    p.add_argument("--json", action="store_true", help="print the raw results as JSON")
    return p.parse_args()


def fetch(args, token):
    body = {
        "urls": args.urls,
        "language": args.lang,
        "outputFormat": args.format,
        "maxVideos": args.max_videos,
        "includeAutoGenerated": not args.no_auto,
    }
    if args.translate:
        body["translateTo"] = args.translate
    max_cost = round(args.max_videos * PRICE_USD, 4)
    req = urllib.request.Request(
        f"{ENDPOINT}?timeout=300&maxTotalChargeUsd={max_cost}",
        data=json.dumps(body).encode(),
        headers={"Authorization": f"Bearer {token}", "Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=330) as res:
            return json.load(res)
    except urllib.error.HTTPError as err:
        if err.code == 408:
            sys.exit("The run took longer than 5 minutes. Ask for fewer videos with --max-videos.")
        sys.exit(f"Apify API error {err.code}: {err.read().decode(errors='replace')[:500]}")
    except urllib.error.URLError as err:
        sys.exit(f"Could not reach the Apify API: {err.reason}")


def content(item, fmt):
    if fmt in ("srt", "vtt"):
        return item.get(fmt) or ""
    if fmt in ("timestamped", "all"):
        return json.dumps(item, ensure_ascii=False, indent=2)
    return item.get("transcript") or ""


def header(item):
    notes = [item.get("language") or "?"]
    if item.get("isAutoGenerated"):
        notes.append("auto-generated")
    if item.get("isTranslated"):
        notes.append("translated")
    if item.get("translationError"):
        notes.append(f"translation failed: {item['translationError']}")
    return f"# {item.get('title') or item['videoId']}\n{item['videoUrl']} ({', '.join(notes)})"


def main():
    args = parse_args()
    token = os.environ.get("APIFY_TOKEN")
    if not token:
        sys.exit(TOKEN_HELP)

    items = fetch(args, token)
    if args.json:
        print(json.dumps(items, ensure_ascii=False, indent=2))
        return
    if not items:
        sys.exit("No videos found for these links.")

    if args.out:
        os.makedirs(args.out, exist_ok=True)
    for item in items:
        if item.get("error"):
            print(f"# {item.get('title') or item['videoId']}\n{item['videoUrl']}\nNo transcript: {item['error']}\n")
            continue
        if args.out:
            path = os.path.join(args.out, f"{item['videoId']}.{EXTENSIONS[args.format]}")
            with open(path, "w", encoding="utf-8") as f:
                f.write(content(item, args.format))
            print(f"{path}  {item.get('title') or ''}")
        else:
            print(f"{header(item)}\n\n{content(item, args.format)}\n")


if __name__ == "__main__":
    main()
